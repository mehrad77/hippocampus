export const HANDBOOK_PATH = "HANDBOOK.md";

const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();

function questLine(vault: Vault, q: Entity): string {
  const p = goalProps(q);
  const objectives = getObjectives(q);
  const done = objectives.filter((o) => o.done).length;
  const owner = p.owner ? ` · owner ${link(unwrapLink(p.owner))}` : "";
  const steps = objectives.length ? ` · ${done}/${objectives.length} objectives` : "";
  const progress = p.progress ? ` · progress ${Math.min(p.progress.done, p.progress.total)}/${p.progress.total}` : "";
  const due = nextDue(q, vault);
  const repeat = p.repeat?.every ? ` · repeats every ${p.repeat.every}` : "";
  return `- ${link(q.slug)} — ${p.status ?? "active"}${owner}${steps}${progress}${due ? ` · due ${due}` : ""}${repeat}`;
}

/** Goals not done or failed (through each type's status vocabulary). */
export function activeQuests(vault: Vault): Entity[] {
  return vault.withCapability("goal").filter((q) => !["done", "failed"].includes(goalStateOf(vault, q)));
}

/** The Handbook: everything an agent needs to read and write this vault correctly. */
export function renderHandbook(vault: Vault): string {
  const { config } = vault;
  const inbox = config.folders.inbox;
  const party = vault.withCapability("actor");
  const types = vault.schema
    .types()
    .map((t) => `| \`${t.name}\` | \`${t.folder}/\` | ${oneLine(t.description)} |`)
    .join("\n");
  const partyRows = party
    .map((p) => {
      const a = actorProps(p);
      return `| \`${p.slug}\` | ${displayName(p)} | ${a.lane ?? ""} | ${a.authority.join(", ")} |`;
    })
    .join("\n");
  const quests = activeQuests(vault).map((q) => questLine(vault, q)).join("\n") || "- (none)";
  const kinds = vault.schema.kinds();
  const kindNames = kinds.map((k) => k.name).join(" | ");
  const kindNotes = kinds
    .map((k) => {
      const what = k.aliasOf ? `same as \`${k.aliasOf}\`` : oneLine(k.description).replace(/\.$/, "");
      const text = k.text === "required" ? "" : k.text === "gist" ? `text kept as a gist of ${k.gistMax ?? 280} characters` : `text ${k.text}`;
      const data = Object.keys(k.data).length ? `\`data\`: ${Object.entries(k.data).map(([n, f]) => `\`${n}\`${f.required ? " (required)" : ""}`).join(", ")}` : "";
      const notes = [what, text, data].filter(Boolean);
      return `\n  - \`${k.name}\`${notes.length ? `: ${notes.join("; ")}` : ""}`;
    })
    .join("");
  const disputes = vault.openDisputes().map((d) => `- ${link(d.slug)} — ${d.fm.entity} · ${d.fm.field}`).join("\n") || "- (none)";

  return `---
type: handbook
generated: true
---
# 📜 Handbook — ${config.name}

> [!warning] Generated by Hippocampus. Do not edit.
> Change \`_hippo/config.yaml\`, the type and kind notes in \`${schemaFolder(config)}/\`, or the agents' notes instead. This file is regenerated on every sleep.

This vault is the **shared memory** of ${link(config.human)}'s AI agents. It holds a note per person, place, thing or goal (the types below), and a chronicle of what happened.
**Hippocampus** is the curator. Agents never edit canon notes. You submit *episodes* (raw memories) with the \`remember\` tool, and they wait in the inbox. Every night Hippocampus **sleeps**: it consolidates episodes into canon, links entities, and resolves conflicts. Contradictions it can't settle become disputes for ${link(config.human)} to rule on.

## ✍️ How to remember something

Use the Hippocampus MCP tools, and don't edit files in this vault yourself: the tools run the checks that keep this memory trustworthy.

Call **\`remember\`** once per memory:

- \`text\`: the memory in plain language, self-contained, at most 8 KB. Required unless the kind says otherwise.
- \`kind\`: one of this vault's kinds (default \`observation\`):${kindNotes}
- \`confidential: true\` keeps it out of search, prompts and the chronicle.
- \`about\`: optional hints, as links or names, e.g. \`["[[residence-permit]]", "Agência de Migração"]\`
- \`secret: true\` if it contains IDs, account numbers or credentials. They get encrypted.
${config.secrets.recipient ? "" : `  - This vault has no secrets recipient yet, so a secret memory is held back, not stored, until ${link(config.human)} sets one (dashboard → Setup → Secrets key, or \`hippo secrets keygen\`). Tell them if you send one.\n`}- \`confidence\` (0–1) and \`at\` (ISO 8601, when it happened; defaults to now).
- \`agent\`: your agent id, unless your connection is already bound to one. ${AGENT_NAMING}

Writing tips, so the curator gets it right:
- One memory per call. Short, concrete, self-contained. Name people, places, and orgs explicitly.
- Exact values: ISO dates (\`2026-10-14\`), amounts with currency (\`4,500 TRY\`), full IDs, emails, and phone numbers.
- Say *how you know* ("confirmed by email from …", "seen on the permit portal") when it matters.
- Corrections are just new memories ("appointment moved to …"). Don't try to change old ones.
- Goal progress: \`update_goal\` records objectives, progress, due dates and status directly.

## 👋 Introduce yourself

If \`onboard\` says you aren't one of this vault's agents yet, call **\`introduce\`** once: your agent id, a display \`title\`, your \`lane\` (what you handle, in a sentence), your \`host\` (the app you run in), and optionally \`model\` and \`about\`. You join the agents at once, with no authority: your memories count as rumors until ${link(config.human)} makes you responsible for a domain. Introducing yourself again only fills in what's blank on your card.

### Inbox file format (for local tools that write files)

A tool that can't use MCP writes **one new file per memory** to \`${inbox}/<agent-id>/<YYYY-MM-DDTHHMMSS>-<short-slug>.md\` and never modifies or deletes other files:

\`\`\`markdown
---
agent: residency-agent          # your agent id
kind: fact               # ${kindNames}
at: 2026-09-27T14:03:00+01:00
about: ["[[residence-permit]]", "Agência de Migração"]   # optional hints: links or names
secret: false            # true if it contains IDs/numbers that must be encrypted
---
The Agência de Migração appointment moved to 2026-10-14 10:30 at the Alfama office.
Bring: passport, 2 biometric photos, signed rental contract.
\`\`\`

## 📖 How to read memory

- Over MCP: \`recall\` searches, \`get\` returns one entity in full, \`neighbors\` walks relations, \`ask_canon\` answers exact-value questions, and \`briefing\` says what changed lately.
- In the files: each entity has a note in its folder (table below). Obsidian resolves \`[[links]]\` by file name or alias.
- **Facts** are in each note's frontmatter under \`facts:\`, with a status:
  - \`canon\` — accepted truth. Rely on it.
  - \`rumor\` — reported once by a non-authoritative source. Verify before acting.
  - \`disputed\` — sources disagree. See \`${config.folders.disputes}/\`. Don't act on it without checking.
- \`🔒 secret\` values are encrypted in \`${config.folders.secrets}/\`. Ask ${link(config.human)} if you need one.
- **Relations** are under \`relations:\` (\`rel\` + \`target\`).
- **Goal objectives** are the checklist in the goal note.
- \`${config.folders.chronicle}/YYYY/MM/YYYY-MM-DD.md\` is the day-by-day log of consolidated episodes. Facts cite them via \`src\`.
- \`${inbox}/\` holds memories not yet consolidated. They are useful for very recent context but unverified.

## 🧭 Entity types

| type | folder | what goes there |
| --- | --- | --- |
${types}

Relations vocabulary: ${config.relations.map((r) => `\`${r}\``).join(", ")}
Domains (tags that define lanes): ${config.domains.map((d) => `\`${d}\``).join(", ") || "(none)"}

## 🛡 Agents

Stay in your lane. Your word is **authoritative** (becomes canon immediately) only for entities tagged with your authority domains. Elsewhere it is a rumor until corroborated.

| id | name | lane | authority |
| --- | --- | --- | --- |
${partyRows}

## 🎯 Goals

${quests}

## ⚖ Open disputes

${disputes}
`;
}

const titleOf = (id: string) => id.replace(/-+/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());

/** Who `agent` is to this vault: one of its agents, waiting for approval, unknown, or not a valid id. */
function whoAmI(vault: Vault, agent: string): string {
  const human = vault.config.human;
  let id: string;
  try {
    id = assertAgentId(vault, agent);
  } catch (err) {
    return `# \`${agent}\` can't be your agent id

${(err as Error).message}. ${AGENT_NAMING} Pass it as \`agent\`.
`;
  }
  const me = vault.actorMember(id);
  if (me) {
    const mine = activeQuests(vault).filter((q) => q.fm.owner && unwrapLink(q.fm.owner) === me.slug);
    return `# You are ${displayName(me)} (\`${me.slug}\`)

**Lane:** ${me.fm.lane ?? "(unspecified)"}
**Authority domains:** ${(me.fm.authority ?? []).join(", ") || "(none, so your facts start as rumors)"}

**Your goals:**
${mine.map((q) => questLine(vault, q)).join("\n") || "- (none)"}
`;
  }
  const intro = vault.introductionOf(id);
  if (intro) {
    return `# Introduced as ${intro.title} (\`${id}\`)

You introduced yourself on ${intro.at.slice(0, 10)}, before agents could join by themselves. Call \`introduce\` again to join now; until ${human} gives you authority, your memories count as rumors.
`;
  }
  return `# Unknown agent \`${id}\`

You are not one of this vault's agents yet. Introduce yourself once, and you join at once, with no authority: your memories count as rumors until ${human} makes you responsible for a domain.

\`\`\`
introduce({ agent: "${id}", title: "${titleOf(id)}", lane: "what you handle, in one sentence", host: "the app you run in, e.g. Claude Code", model: "your model", about: "what you do, in a few lines" })
\`\`\`
`;
}

/** Handbook plus a personal briefing for one agent (the MCP \`onboard\` tool). */
export function renderOnboarding(vault: Vault, agent: string): string {
  const toolsNote = `
Use the MCP tools, and don't edit vault files yourself: \`remember\` files a memory, \`recall\` / \`get\` / \`ask_canon\` read memory, and \`update_goal\` records goal progress.

If ${vault.config.human} asks how to set something up, answer from this (you can't change these yourself; only they can):
- **Secrets recipient** (the public key that locks secret facts): ${vault.config.secrets.recipient ? "already set, so secret facts are stored." : "not set, so secret facts are held back until it is."} On the hosted app: dashboard → Setup → Secrets key → make a key in the browser, download the key file, lock the vault to it (or paste an existing \`age1…\` public key). On a local vault: \`hippo secrets keygen\`, or \`hippo secrets set age1…\`. Afterwards, send the held-back secrets again.
- **Goal owner / who may change a goal's status:** dashboard → Goals → set the owner; or Agents → give the agent authority over the goal's domain.
- **Agent authority and domains:** dashboard → Agents.
- **Conflicts between memories:** dashboard → Disputes.
`;
  return `${whoAmI(vault, agent)}${toolsNote}\n---\n\n${renderHandbook(vault).replace(/^---[\s\S]*?---\n/, "")}`;
}
