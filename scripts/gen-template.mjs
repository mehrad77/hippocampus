// Bundles vault-template/ and seeds/ into packages/template/src/files.gen.ts, so a runtime without
// a filesystem (the hosted Worker) can build a vault with `buildVaultFiles`. Run `pnpm gen:template`
// after changing either folder; scripts/gen-template.test.ts fails while the bundle is stale.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const OUT = "packages/template/src/files.gen.ts";

const byPath = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const utf8 = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

/**
 * What git would commit under `dir` (tracked, or new and not ignored), relative to it. Going through
 * git keeps out what .gitignore keeps out: local seeds/private-*, editor and OS files.
 */
function committable(dir) {
  const out = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", dir], { cwd: ROOT, encoding: "utf8" });
  return out
    .split("\0")
    .filter((p) => p && existsSync(join(ROOT, p)))
    .map((p) => p.slice(dir.length + 1))
    .sort(byPath);
}

function read(dir, paths) {
  const files = {};
  for (const p of paths) {
    try {
      files[p] = utf8.decode(readFileSync(join(ROOT, dir, p)));
    } catch {
      throw new Error(`${dir}/${p} is not UTF-8 text; the bundled template holds text files only`);
    }
  }
  return files;
}

/** The template's files and each seed's files, by vault-relative path. */
export function collect() {
  // The repo keeps the template's real `.gitignore` (only the npm package renames it), so paths map 1:1.
  const template = read("vault-template", committable("vault-template"));
  const bySeed = new Map();
  for (const p of committable("seeds")) {
    const [name, ...rest] = p.split("/");
    // Private seeds hold real data; they never belong in a public bundle, ignored or not.
    if (!rest.length || name.startsWith("private-")) continue;
    bySeed.set(name, [...(bySeed.get(name) ?? []), rest.join("/")]);
  }
  const seeds = {};
  for (const name of [...bySeed.keys()].sort(byPath)) seeds[name] = read(`seeds/${name}`, bySeed.get(name));
  return { template, seeds };
}

const entries = (files, indent) => Object.entries(files).map(([p, content]) => `${indent}${JSON.stringify(p)}: ${JSON.stringify(content)},\n`).join("");

/** The generated module's source. */
export function render({ template, seeds } = collect()) {
  const seedBlocks = Object.entries(seeds)
    .map(([name, files]) => `  ${JSON.stringify(name)}: {\n${entries(files, "    ")}  },\n`)
    .join("");
  return `// generated by scripts/gen-template.mjs — do not edit. Run \`pnpm gen:template\` to update it.

/** Every file of vault-template/, by vault-relative path. */
export const TEMPLATE: Record<string, string> = {
${entries(template, "  ")}};

/** The example campaigns in seeds/, by name. Each is laid over TEMPLATE (see buildVaultFiles). */
export const SEEDS: Record<string, Record<string, string>> = {
${seedBlocks}};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(join(ROOT, OUT), render());
  console.log(`✓ wrote ${OUT}`);
}
